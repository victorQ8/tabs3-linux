"""Extract AMS968HH01 normal-brightness constants from pinned Samsung GPL source.

Usage: generate-data.py common.c panel.h panel.dtsi output.h
Source commit: f48aec90fcebf4615fdee4a8abac7339930db856 in
awesometic/android_kernel_samsung_msm8996. Generated data excludes HBM.
"""
import hashlib
import pathlib
import re
import sys


def clean(text):
    return re.sub(r'/\*.*?\*/|//[^\n]*', '', text, flags=re.S)


def array(text, name, width):
    match = re.search(r'\b' + re.escape(name) + r'\s*(?:\[[^\]]*\])+\s*=\s*\{(.*?)\};', clean(text), re.S)
    assert match, name
    values = [int(x, 0) for x in re.findall(r'-?0x[0-9a-fA-F]+|-?\d+', match[1])]
    assert len(values) % width == 0, name
    return [values[i:i + width] for i in range(0, len(values), width)]


def prop(text, name, width=None):
    match = re.search(r'samsung,' + re.escape(name) + r'\s*=\s*([<\[])(.*?)[>\]];', clean(text), re.S)
    assert match, name
    values = [int(x, 16 if match[1] == '[' else 0) for x in match[2].split()]
    if width:
        assert len(values) % width == 0
        return [values[i:i+width] for i in range(0, len(values), width)]
    result = []
    while values:
        size = values[5] * 256 + values[6]
        assert len(values) >= size + 7 and values[0] == 0x39
        result.append(values[7:7+size])
        values = values[7+size:]
    return result


def main():
    common_path, header_path, dtsi_path, output = map(pathlib.Path, sys.argv[1:])
    expected = (
        '202dc5d6a3b2a813b57dcc4719ea5cc7570a4c0f293b83c099fd26afcb8df7b2',
        '9abbf04ad28f9f5c9525606f73accd9dc306aa967d1f269c04e0b90cc0e92f59',
        'b429ceeaa27276b556b11a17319ee7f11767f8099f91aefa3b5e4e344f837546',
    )
    for path, digest in zip((common_path, header_path, dtsi_path), expected):
        if hashlib.sha256(path.read_bytes()).hexdigest() != digest:
            raise SystemExit(f'Not the pinned Samsung source: {path}')
    common, header, dtsi = (p.read_text() for p in [common_path, header_path, dtsi_path])
    lines = ['// SPDX-License-Identifier: GPL-2.0-only',
             '/* Copyright (C) 2012 Samsung Electronics. All rights reserved.',
             ' * Generated by tools/panel/generate-data.py; do not edit.',
             ' * Source: awesometic/android_kernel_samsung_msm8996',
             ' * commit f48aec90fcebf4615fdee4a8abac7339930db856.']
    for p in [common_path, header_path, dtsi_path]:
        lines.append(' * ' + p.name + ' SHA256 ' + hashlib.sha256(p.read_bytes()).hexdigest())
    lines += [' */', '#ifndef AMS968HH01_DIMMING_DATA_H', '#define AMS968HH01_DIMMING_DATA_H', '']

    def emit(name, typ, rows):
        width = len(rows[0])
        suffix = f'[{width}]' if width > 1 else ''
        lines.append(f'static const {typ} {name}[{len(rows)}]{suffix} = {{')
        for row in rows:
            lines.append('\t' + ('{ ' if width > 1 else '') + ', '.join(map(str, row)) + (' },' if width > 1 else ','))
        lines.extend(['};', ''])

    for source, name in [('candela_coeff_2p15', 'ams_coeff_215'), ('curve_2p2_360', 'ams_curve_360')]:
        rows = array(common, source, 1); assert len(rows) == 256
        emit(name, 'u32', rows)
    cd = array(header, 'candela_table', 2)
    base = array(header, 'base_luminance_revA', 2)
    grad = array(header, 'gradation_offset_revA', 9)
    rgb = array(header, 'rgb_offset_revA', 24)
    assert len(cd) == len(base) == len(grad) == len(rgb) == 65
    assert [x[0] for x in cd] == [x[0] for x in base]
    emit('ams_candela', 'u16', [[x[0]] for x in cd])
    emit('ams_base_luminance', 'u16', [[x[1]] for x in base])
    emit('ams_gradation', 's16', grad)
    emit('ams_rgb_offset', 's16', rgb)
    candela = prop(dtsi, 'candela_map_table_revA', 4)
    aid = prop(dtsi, 'aid_subdivision_tx_cmds_revA')
    caps = prop(dtsi, 'caps_setting_tx_cmds_revA')
    capsmap = dict(prop(dtsi, 'caps_map_table_revA', 2))
    elvss = prop(dtsi, 'smart_acl_elvss_tx_cmds_revA')
    elvssmap = dict(prop(dtsi, 'smart_acl_elvss_map_table_revA', 2))
    assert len(aid) == 256 and len(candela) == 65
    levels = [None] * 256
    for idx, start, end, nit in candela:
        assert cd[idx] == [nit, idx]
        for level in range(start, end+1):
            a = aid[level]; e = elvss[elvssmap[nit]]; c = caps[capsmap[nit]]
            assert len(a) == 4 and a[0] == 0x90 and a[2] == 0 and a[1] <= 1
            assert len(e) == len(c) == 2 and e[0] == c[0] == 0xb2
            assert levels[level] is None
            levels[level] = [idx, a[1], a[3], e[1], c[1]]
    assert all(levels)
    lines.append('/* Per stock level: gamma row, AID high, AID low, normal-temperature ELVSS, CAPS. */')
    emit('ams_brightness_data', 'u8', levels)
    lines += ['#endif', '']
    output.write_text('\n'.join(lines))


if __name__ == '__main__':
    main()
